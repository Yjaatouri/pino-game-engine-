bool Font::load_builtin() {
    destroy();

    // Allocate RGBA pixel buffer for atlas
    u32 atlas_pixels[ATLAS_W * ATLAS_H] = {};
    u32 pixel_count = ATLAS_W * ATLAS_H;

    // Decode monochrome bits into RGBA atlas
    for (u32 ci = 0; ci < FONT_COUNT; ++ci) {
        u32 col = ci % FONT_COLS;
        u32 row = ci / FONT_COLS;
        u32 origin_x = col * FONT_GLYPH_W;
        u32 origin_y = row * FONT_GLYPH_H;

        for (u32 py = 0; py < FONT_GLYPH_H; ++py) {
            u8 bits = s_font_bits[ci][py];
            for (u32 px = 0; px < FONT_GLYPH_W; ++px) {
                bool on = (bits >> (7 - px)) & 1;
                u32 idx = (origin_y + py) * ATLAS_W + (origin_x + px);
                if (idx < pixel_count) {
                    atlas_pixels[idx] = on ? 0xFFFFFFFF : 0x00000000;
                }
            }
        }
    }

    // Upload atlas to GPU
    m_atlas.upload_rgba(reinterpret_cast<const u8*>(atlas_pixels),
                        static_cast<i32>(ATLAS_W),
                        static_cast<i32>(ATLAS_H));

    // Override to nearest-neighbour filtering for crisp pixel font
    glBindTexture(GL_TEXTURE_2D, m_atlas.handle());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);

    // Populate glyph metrics
    for (u32 ci = 0; ci < FONT_COUNT; ++ci) {
        u32 ch = ci + FONT_FIRST;
        if (ch >= 128) break;

        u32 gcol = ci % FONT_COLS;
        u32 grow = ci / FONT_COLS;

        Glyph& g = m_glyphs[ch];
        g.width     = static_cast<f32>(FONT_GLYPH_W);
        g.height    = static_cast<f32>(FONT_GLYPH_H);
        g.advance   = static_cast<f32>(FONT_GLYPH_W);
        g.bearing_x = 0;
        g.bearing_y = static_cast<f32>(FONT_GLYPH_H);

        // UV: pixel row 0 = top of glyph, GL maps row 0 to v=0 (bottom of texture),
        // so (v0,v1) = (0/total, h/total) — top of quad samples row 0 = top of glyph.
        f32 left  = static_cast<f32>(gcol * FONT_GLYPH_W) / static_cast<f32>(ATLAS_W);
        f32 right = static_cast<f32>((gcol + 1) * FONT_GLYPH_W) / static_cast<f32>(ATLAS_W);

        g.u0 = left;
        g.v0 = static_cast<f32>(grow * FONT_GLYPH_H) / static_cast<f32>(ATLAS_H);
        g.u1 = right;
        g.v1 = static_cast<f32>((grow + 1) * FONT_GLYPH_H) / static_cast<f32>(ATLAS_H);
    }

    m_font_size   = static_cast<f32>(FONT_GLYPH_H);
    m_line_height = static_cast<f32>(FONT_GLYPH_H + 2);
    m_valid       = true;

    PINO_INFO("Built-in font loaded: %ux%u atlas, %u glyphs",
              ATLAS_W, ATLAS_H, FONT_COUNT);
    return true;
}

bool Font::load(const char* atlas_path, FileSystem& fs) {
    destroy();

    if (!atlas_path || !atlas_path[0]) {
        PINO_ERROR("Font::load: null or empty path");
        return false;
    }

    m_loaded_data = fs.read_binary(atlas_path);
    if (m_loaded_data.empty()) {
        PINO_ERROR("Font::load: failed to read '%s' — file missing or empty", atlas_path);
        return false;
    }

    i32 channels = 0;
    stbi_set_flip_vertically_on_load(1);
    unsigned char* pixels = stbi_load_from_memory(
        m_loaded_data.data(), static_cast<i32>(m_loaded_data.size()),
        &m_image_w, &m_image_h, &channels, 4);

    if (!pixels) {
        PINO_ERROR("Font::load: stb_image failed to decode '%s'", atlas_path);
        m_loaded_data.clear();
        return false;
    }

    usize pixel_count = static_cast<usize>(m_image_w) * static_cast<usize>(m_image_h) * 4;
    m_decoded_pixels.assign(pixels, pixels + pixel_count);
    stbi_image_free(pixels);

    // Upload to GPU
    m_atlas.upload_rgba(m_decoded_pixels.data(), m_image_w, m_image_h);

    // Override to nearest-neighbour filtering for crisp pixel font
    glBindTexture(GL_TEXTURE_2D, m_atlas.handle());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);

    // Free CPU-side image data now that GPU has a copy
    m_loaded_data.clear();
    m_loaded_data.shrink_to_fit();
    m_decoded_pixels.clear();
    m_decoded_pixels.shrink_to_fit();

    // Derive metrics file path from atlas path
    std::string metrics_path(atlas_path);
    {
        auto dot = metrics_path.rfind('.');
        if (dot != std::string::npos && dot > metrics_path.rfind('/')
            && dot > metrics_path.rfind('\\'))
            metrics_path.resize(dot);
        metrics_path += ".fnt";
    }

    std::string metrics_text = fs.read_text(metrics_path.c_str());
    if (metrics_text.empty()) {
        PINO_ERROR("Font::load: failed to read metrics '%s'", metrics_path.c_str());
        return false;
    }

    // Parse metrics: one line per char, fields = char_id x y w h xoff yoff advance
    f32 atlas_w = static_cast<f32>(m_atlas.width());
    f32 atlas_h = static_cast<f32>(m_atlas.height());
    int parsed = 0;

    std::istringstream stream(metrics_text);
    std::string line;
    while (std::getline(stream, line)) {
        if (line.empty() || line[0] == '#') continue;
        int id = 0, x = 0, y = 0, w = 0, h = 0, xoff = 0, yoff = 0, adv = 0;
        if (std::sscanf(line.c_str(), "%d %d %d %d %d %d %d %d",
                        &id, &x, &y, &w, &h, &xoff, &yoff, &adv) != 8)
            continue;
        if (id < 0 || id >= 128) continue;

        Glyph& g = m_glyphs[id];
        g.width     = static_cast<f32>(w);
        g.height    = static_cast<f32>(h);
        g.bearing_x = static_cast<f32>(xoff);
        g.bearing_y = static_cast<f32>(yoff);
        g.advance   = static_cast<f32>(adv);
        g.u0 = static_cast<f32>(x)      / atlas_w;
        g.v0 = 1.0f - static_cast<f32>(y) / atlas_h;
        g.u1 = static_cast<f32>(x + w)  / atlas_w;
        g.v1 = 1.0f - static_cast<f32>(y + h) / atlas_h;

        ++parsed;
    }

    if (parsed == 0) {
        PINO_ERROR("Font::load: no valid glyph entries in '%s'", metrics_path.c_str());
        return false;
    }

    // ── Validate parsed glyph data ──────────────────────────────
    int errors = 0;
    bool has_printable[95] = {};
    for (int i = 0; i < 128; ++i) {
        const Glyph& g = m_glyphs[i];
        if (g.width == 0 && g.height == 0 && g.advance == 0
            && g.u0 == 0 && g.v0 == 0 && g.u1 == 0 && g.v1 == 0)
            continue;
        if (i >= 32 && i <= 126) has_printable[i - 32] = true;

        if (g.width < 0 || g.height < 0)
            { PINO_ERROR("  [%d] negative size: %.0fx%.0f", i, g.width, g.height); ++errors; }
        if (g.advance <= 0)
            { PINO_ERROR("  [%d] advance <= 0: %.1f", i, g.advance); ++errors; }
        if (g.advance < g.width)
            { PINO_WARN("  [%d] advance < width: %.1f < %.1f", i, g.advance, g.width); ++errors; }
        if (g.u0 < 0 || g.u0 > 1 || g.u1 < 0 || g.u1 > 1
            || g.v0 < 0 || g.v0 > 1 || g.v1 < 0 || g.v1 > 1)
            { PINO_ERROR("  [%d] UV out of [0,1]: (%.3f,%.3f)-(%.3f,%.3f)",
                         i, g.u0, g.v0, g.u1, g.v1); ++errors; }
        if (g.u1 <= g.u0)
            { PINO_ERROR("  [%d] u1 <= u0: %.3f <= %.3f", i, g.u1, g.u0); ++errors; }
        if (g.v0 == g.v1)
            { PINO_WARN("  [%d] v0 == v1 (zero-height glyph)", i); ++errors; }
    }

    // Check that all printable ASCII (32–126) are present
    for (int i = 0; i < 95; ++i) {
        if (!has_printable[i]) {
            PINO_ERROR("  [%d] missing glyph for printable char '%c'", i + 32, i + 32);
            ++errors;
        }
    }

    if (errors > 0) {
        PINO_ERROR("Font::load: %d validation error(s) in '%s'", errors, metrics_path.c_str());
        return false;
    }

    PINO_INFO("Font::load: '%s' + '%s' (%d glyphs, %dx%d atlas, validated OK)",
              atlas_path, metrics_path.c_str(), parsed, m_image_w, m_image_h);
    m_valid = true;
    return true;
}

void Font::destroy() {
    m_atlas.destroy();
    m_loaded_data.clear();
    m_loaded_data.shrink_to_fit();
    m_decoded_pixels.clear();
    m_decoded_pixels.shrink_to_fit();
    m_image_w = 0;
    m_image_h = 0;
    for (int i = 0; i < 128; ++i)
        m_glyphs[i] = Glyph{};
    m_font_size   = 16.0f;
    m_line_height = 20.0f;
    m_valid       = false;
}

const Font::Glyph& Font::glyph(char c) const {
    static Glyph null_glyph{};
    u8 idx = static_cast<u8>(c);
    if (idx >= 128) return null_glyph;
    return m_glyphs[idx];
}

f32 Font::font_size() const { return m_font_size; }
f32 Font::line_height() const { return m_line_height; }
bool Font::is_valid() const { return m_valid; }
Texture& Font::atlas() { return m_atlas; }

Font::~Font() { destroy(); }

Font::Font(Font&& other) noexcept
    : m_atlas(std::move(other.m_atlas))
    , m_loaded_data(std::move(other.m_loaded_data))
    , m_decoded_pixels(std::move(other.m_decoded_pixels))
    , m_image_w(other.m_image_w)
    , m_image_h(other.m_image_h)
    , m_font_size(other.m_font_size)
    , m_line_height(other.m_line_height)
    , m_valid(other.m_valid)
{
    for (int i = 0; i < 128; ++i)
        m_glyphs[i] = other.m_glyphs[i];
    other.m_valid = false;
}

Font& Font::operator=(Font&& other) noexcept {
    if (this != &other) {
        m_atlas          = std::move(other.m_atlas);
        m_loaded_data    = std::move(other.m_loaded_data);
        m_decoded_pixels = std::move(other.m_decoded_pixels);
        m_image_w        = other.m_image_w;
        m_image_h        = other.m_image_h;
        m_font_size      = other.m_font_size;
        m_line_height    = other.m_line_height;
        m_valid          = other.m_valid;
        for (int i = 0; i < 128; ++i)
            m_glyphs[i] = other.m_glyphs[i];
        other.m_valid = false;
    }
    return *this;
}

